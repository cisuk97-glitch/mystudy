CREATE POLICY "Public all lessons" ON lessons FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public all vocab_words" ON vocab_words;
CREATE POLICY "Public all vocab_words" ON vocab_words FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public all test_records" ON test_records;
CREATE POLICY "Public all test_records" ON test_records FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public all test_wrong_history" ON test_wrong_history;
CREATE POLICY "Public all test_wrong_history" ON test_wrong_history FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public all app_meta" ON app_meta;
CREATE POLICY "Public all app_meta" ON app_meta FOR ALL TO anon USING (true) WITH CHECK (true);

