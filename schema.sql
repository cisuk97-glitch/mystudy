-- 1. 대단원 테이블 (lessons)
CREATE TABLE IF NOT EXISTS lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 단어 테이블 (vocab_words)
CREATE TABLE IF NOT EXISTS vocab_words (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT REFERENCES lessons(id) ON DELETE CASCADE,
    word_no INTEGER NOT NULL,
    word TEXT NOT NULL,
    pos TEXT,
    meaning TEXT NOT NULL,
    eng_def TEXT,
    test_count INTEGER DEFAULT 0,
    wrong_count INTEGER DEFAULT 0,
    is_mastered BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_lesson_word UNIQUE(lesson_id, word_no)
);

-- 인덱스 생성 (성능 최적화)
CREATE INDEX IF NOT EXISTS idx_vocab_lesson ON vocab_words(lesson_id);
CREATE INDEX IF NOT EXISTS idx_vocab_wrong ON vocab_words(lesson_id, wrong_count DESC);

-- 3. 회차별 성적 이력 (test_records)
CREATE TABLE IF NOT EXISTS test_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT REFERENCES lessons(id) ON DELETE CASCADE,
    test_category TEXT NOT NULL DEFAULT 'VOCAB', -- 'VOCAB' | 'UNIT' | 'WRITING'
    test_title TEXT,                             -- 상세 시험명 (예: '3과 본문 핵심 서술형 영작')
    round INTEGER NOT NULL,
    test_mode TEXT NOT NULL DEFAULT 'ALL',       -- 'ALL' | 'WRONG_ONLY'
    score INTEGER NOT NULL,
    correct_count INTEGER NOT NULL,
    total_count INTEGER NOT NULL,
    stars_won INTEGER NOT NULL,
    test_date TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT chk_test_category CHECK (test_category IN ('VOCAB', 'UNIT', 'WRITING'))
);

CREATE INDEX IF NOT EXISTS idx_records_lesson ON test_records(lesson_id);
CREATE INDEX IF NOT EXISTS idx_records_category ON test_records(lesson_id, test_category);
CREATE INDEX IF NOT EXISTS idx_records_date ON test_records(test_date DESC);

-- 4. 회차별 오답 상세 로그 (test_wrong_history)
CREATE TABLE IF NOT EXISTS test_wrong_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id BIGINT REFERENCES test_records(id) ON DELETE CASCADE,
    word_id BIGINT REFERENCES vocab_words(id) ON DELETE CASCADE,
    user_answer TEXT,
    correct_answer TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_wrong_history_record ON test_wrong_history(record_id);
CREATE INDEX IF NOT EXISTS idx_wrong_history_word ON test_wrong_history(word_id);

-- 5. 앱 메타데이터 테이블 (app_meta)
CREATE TABLE IF NOT EXISTS app_meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- --------------------------------------------------------
-- Row Level Security (RLS) 설정
-- 웹 프론트엔드(익명 키 anon)에서 직접 읽기/쓰기가 가능하도록 허용
